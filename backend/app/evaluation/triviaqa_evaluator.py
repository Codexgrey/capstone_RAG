"""
backend/app/evaluation/triviaqa_evaluator.py
============================================
TriviaQA-based evaluation for the Capstone RAG System.

Dataset
-------
Built from the official TriviaQA dev splits (Joshi et al., ACL 2017):
  - wikipedia-dev.json  (7,993 questions)
  - web-dev.json        (9,951 questions)

Selection: 4,000 from Wikipedia dev + 1,000 Web-only (not in Wikipedia dev)
           = 5,000 questions total, deduplicated, quality-filtered.

  Domain breakdown : {'Wikipedia': 4000, 'Web': 1000}
  Answer types     : {'WikipediaEntity': 4674, 'FreeForm': 133, 'Numerical': 184, 'Range': 9}
  Avg aliases/Q    : 12.9
  Seed             : 42 (reproducible)

How it is used
--------------
TriviaQA is used as an evaluation **benchmark**, not as a document corpus.
The RAG system ingests its own documents normally. This module sends the
TriviaQA questions through the live pipeline and scores the generated
answers against all valid answer aliases using the official TriviaQA
Exact Match (EM) and token-level F1 functions.

This gives the project externally validated, citable metrics that go
beyond the internal cosine-similarity threshold proxy, and are directly
comparable to results reported in the TriviaQA paper.

Citation
--------
Mandar Joshi, Eunsol Choi, Daniel Weld, Luke Zettlemoyer.
"TriviaQA: A Large Scale Distantly Supervised Challenge Dataset for
Reading Comprehension." ACL 2017.
https://arxiv.org/abs/1705.03551

Public API
----------
    score_single(predicted, answer_object)   -> dict  # EM + F1 for one answer
    get_test_questions(n, domain, qtype)     -> list  # question list for frontend
    get_question_by_id(qid)                  -> dict  # lookup single question
    run_triviaqa_batch(...)                  -> dict  # batch evaluation runner
    TRIVIAQA_BANK                            -> list  # full 5000-entry bank
"""

from __future__ import annotations

import json
import re
import string
from collections import Counter
from typing import Any, Callable, Dict, List, Optional


# ---------------------------------------------------------------------------
# 5,000-question bank  (loaded from triviaqa_bank.json at import time)
# ---------------------------------------------------------------------------

from pathlib import Path

_BANK_PATH = Path(__file__).parent / "triviaqa_bank.json"
TRIVIAQA_BANK: List[Dict[str, Any]] = json.loads(_BANK_PATH.read_text(encoding="utf-8"))


# Fast lookup by QuestionId
_BANK_INDEX: Dict[str, Dict[str, Any]] = {
    q["QuestionId"]: q for q in TRIVIAQA_BANK
}


# ---------------------------------------------------------------------------
# Official TriviaQA scoring  (ported verbatim from triviaqa_evaluation.py)
# ---------------------------------------------------------------------------

def _normalize_answer(s: str) -> str:
    """Lower text and remove punctuation, articles, and extra whitespace."""
    def remove_articles(text: str) -> str:
        return re.sub(r"\b(a|an|the)\b", " ", text)

    def white_space_fix(text: str) -> str:
        return " ".join(text.split())

    def handle_punc(text: str) -> str:
        exclude = set(string.punctuation + "’‘´`")
        return "".join(ch if ch not in exclude else " " for ch in text)

    return white_space_fix(
        remove_articles(handle_punc(s.lower().replace("_", " ")))
    ).strip()


def _f1_score(prediction: str, ground_truth: str) -> float:
    pred_tokens = _normalize_answer(prediction).split()
    gt_tokens   = _normalize_answer(ground_truth).split()
    common      = Counter(pred_tokens) & Counter(gt_tokens)
    num_same    = sum(common.values())
    if num_same == 0:
        return 0.0
    precision = num_same / len(pred_tokens)
    recall    = num_same / len(gt_tokens)
    return (2 * precision * recall) / (precision + recall)


def _exact_match_score(prediction: str, ground_truth: str) -> float:
    return float(_normalize_answer(prediction) == _normalize_answer(ground_truth))


def _max_over_aliases(
    metric_fn: Callable[[str, str], float],
    prediction: str,
    aliases: List[str],
) -> float:
    return max(metric_fn(prediction, alias) for alias in aliases) if aliases else 0.0


def score_single(
    predicted_answer: str,
    answer_object: Dict[str, Any],
) -> Dict[str, float]:
    """
    Score one predicted answer against a TriviaQA answer object.

    Args:
        predicted_answer : String generated by the RAG pipeline.
        answer_object    : Dict with at minimum 'NormalizedAliases' and/or
                           'NormalizedValue'.  Matches the shape stored in
                           TRIVIAQA_BANK[i]['Answer'].

    Returns:
        {"exact_match": float, "f1": float}  â both in [0.0, 1.0].

    Notes:
        Scoring is max-over-aliases: the prediction is compared against every
        valid alias and the best score is kept.  This is the official TriviaQA
        protocol and is lenient to minor phrasing differences.
    """
    aliases = answer_object.get("NormalizedAliases", [])
    if not aliases:
        nv = answer_object.get("NormalizedValue", "")
        aliases = [nv] if nv else []
    if not aliases:
        return {"exact_match": 0.0, "f1": 0.0}

    em = _max_over_aliases(_exact_match_score, predicted_answer, aliases)
    f1 = _max_over_aliases(_f1_score,          predicted_answer, aliases)
    return {"exact_match": round(em, 4), "f1": round(f1, 4)}


# ---------------------------------------------------------------------------
# Public helpers
# ---------------------------------------------------------------------------

def get_question_by_id(question_id: str) -> Optional[Dict[str, Any]]:
    """Return a single bank entry by QuestionId, or None if not found."""
    return _BANK_INDEX.get(question_id)


def get_test_questions(
    n:      Optional[int] = None,
    domain: Optional[str] = None,   # "Wikipedia" | "Web" | None = both
    qtype:  Optional[str] = None,   # "WikipediaEntity" | "Numerical" | "FreeForm" | None
) -> List[Dict[str, str]]:
    """
    Return a slice of the question bank for frontend display (no answers).

    Args:
        n      : Maximum number of questions to return.  None = all 5,000.
        domain : Filter by domain ("Wikipedia" or "Web").  None = both.
        qtype  : Filter by answer type.  None = all types.

    Returns:
        List of {question_id, question, domain, answer_type} dicts.
    """
    questions = TRIVIAQA_BANK

    if domain:
        questions = [q for q in questions if q["Domain"] == domain]
    if qtype:
        questions = [q for q in questions if q["Answer"].get("Type") == qtype]
    if n is not None:
        questions = questions[:n]

    return [
        {
            "question_id":  q["QuestionId"],
            "question":     q["Question"],
            "domain":       q["Domain"],
            "answer_type":  q["Answer"].get("Type", ""),
        }
        for q in questions
    ]


def get_bank_stats() -> Dict[str, Any]:
    """Return summary statistics about the full bank."""
    domains = {}
    types   = {}
    alias_counts = []
    for q in TRIVIAQA_BANK:
        d = q["Domain"]
        t = q["Answer"].get("Type", "unknown")
        domains[d] = domains.get(d, 0) + 1
        types[t]   = types.get(t, 0) + 1
        alias_counts.append(len(q["Answer"]["NormalizedAliases"]))

    return {
        "total":       len(TRIVIAQA_BANK),
        "domains":     domains,
        "types":       types,
        "avg_aliases": round(sum(alias_counts) / len(alias_counts), 1),
        "min_aliases": min(alias_counts),
        "max_aliases": max(alias_counts),
        "source":      "TriviaQA (Joshi et al., ACL 2017)",
        "splits_used": ["wikipedia-dev", "web-dev"],
    }


# ---------------------------------------------------------------------------
# On-the-fly scoring hook  (called from response_formatter.py)
# ---------------------------------------------------------------------------

def score_if_in_bank(question: str, predicted_answer: str) -> Optional[Dict[str, Any]]:
    """
    Check whether `question` matches any entry in TRIVIAQA_BANK.
    If it does, score `predicted_answer` and return EM/F1 + question_id.
    Returns None if the question is not in the bank.

    This is called on every RAG response so that any time a user happens to
    ask a TriviaQA question during normal use, the answer is automatically
    scored against ground truth.
    """
    if not question or not predicted_answer:
        return None

    q_norm = _normalize_answer(question)
    for item in TRIVIAQA_BANK:
        if _normalize_answer(item["Question"]) == q_norm:
            scores = score_single(predicted_answer, item["Answer"])
            return {
                "triviaqa_em":  scores["exact_match"],
                "triviaqa_f1":  scores["f1"],
                "triviaqa_qid": item["QuestionId"],
            }
    return None


# ---------------------------------------------------------------------------
# Batch evaluation runner
# ---------------------------------------------------------------------------

def run_triviaqa_batch(
    retrieval_method: str = "vector",
    top_k:            int = 5,
    question_ids:     Optional[List[str]] = None,
    n:                Optional[int] = None,
    domain:           Optional[str] = None,
    qtype:            Optional[str] = None,
    rag_query_fn:     Optional[Callable] = None,
) -> Dict[str, Any]:
    """
    Run the TriviaQA benchmark across a subset of the 5,000-question bank.

    Args:
        retrieval_method : "vector", "keyword", or "hybrid".
        top_k            : Chunks to retrieve per question.
        question_ids     : Explicit list of QuestionIds to evaluate.
                           Overrides n/domain/qtype if provided.
        n                : Max questions to evaluate (default: all in selection).
        domain           : Filter by domain ("Wikipedia" | "Web").
        qtype            : Filter by answer type.
        rag_query_fn     : Callable(question, retrieval_method, top_k) -> str
                           Should return the raw answer string.
                           If None, returns the question list without running
                           inference (useful for dry-run / frontend preview).

    Returns:
        {
          "method":    str,
          "total":     int,
          "answered":  int,
          "avg_em":    float,     # official TriviaQA Exact Match
          "avg_f1":    float,     # official TriviaQA token F1
          "results":   [...]
        }
    """
    # Build question list
    if question_ids:
        bank = [_BANK_INDEX[qid] for qid in question_ids if qid in _BANK_INDEX]
    else:
        bank = TRIVIAQA_BANK
        if domain:
            bank = [q for q in bank if q["Domain"] == domain]
        if qtype:
            bank = [q for q in bank if q["Answer"].get("Type") == qtype]
        if n is not None:
            bank = bank[:n]

    results  = []
    total_em = total_f1 = 0.0
    answered = 0

    for item in bank:
        qid      = item["QuestionId"]
        question = item["Question"]
        answer   = item["Answer"]
        predicted = ""
        em = f1 = 0.0

        if rag_query_fn is not None:
            try:
                predicted = rag_query_fn(
                    question         = question,
                    retrieval_method = retrieval_method,
                    top_k            = top_k,
                )
                scores = score_single(predicted, answer)
                em     = scores["exact_match"]
                f1     = scores["f1"]
                answered += 1
            except Exception as exc:
                predicted = f"[error: {exc}]"

        total_em += em
        total_f1 += f1

        results.append({
            "question_id":   qid,
            "question":      question,
            "domain":        item["Domain"],
            "answer_type":   answer.get("Type", ""),
            "predicted":     predicted,
            "ground_truth":  answer["Value"],
            "aliases":       answer["NormalizedAliases"],
            "exact_match":   round(em, 4),
            "f1":            round(f1, 4),
        })

    n_total = len(bank)
    return {
        "method":   retrieval_method,
        "total":    n_total,
        "answered": answered,
        "avg_em":   round(total_em / n_total, 4) if n_total else 0.0,
        "avg_f1":   round(total_f1 / n_total, 4) if n_total else 0.0,
        "results":  results,
    }
